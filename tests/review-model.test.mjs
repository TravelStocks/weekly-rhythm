import assert from 'node:assert/strict';
import {shiftPeriod,quarterMonths,createRecord,validStore,allocation,outcome} from '../docs/review-model.js';
assert.equal(shiftPeriod('monthly','2026-12',1),'2027-01');
assert.equal(shiftPeriod('monthly','2026-01',-1),'2025-12');
assert.equal(shiftPeriod('quarterly','2026-Q4',1),'2027-Q1');
assert.equal(shiftPeriod('quarterly','2026-Q1',-1),'2025-Q4');
assert.deepEqual(quarterMonths('2026-Q4'),['2026-10','2026-11','2026-12']);
const month=createRecord('monthly','2026-10'),other=createRecord('monthly','2026-11'),quarter=createRecord('quarterly','2026-Q4');
month.priorities[0].title='推进项目';month.priorities[0].date='2026-11-15';
month.fields.continue='保留周六复盘';
assert.equal(other.priorities[0].title,'');
assert.equal(validStore('monthly',{schema:1,records:{'2026-10':month,'2026-11':other}}),true);
assert.equal(validStore('quarterly',{schema:1,records:{'2026-10':month}}),false);
assert.equal(outcome('monthly',month)[0].items[0],'推进项目 · 2026-11-15');
quarter.fields={'time-0':'50','time-1':'30','time-2':'20','goal-0':'明确主业成果','skill-focus':'英语口语'};
assert.deepEqual(allocation(quarter.fields),{values:[50,30,20],total:100,valid:true});
assert.equal(allocation({'time-0':'101'}).valid,false);
assert.equal(outcome('quarterly',quarter)[0].items[0],'主业：明确主业成果');
assert.equal(outcome('quarterly',quarter)[1].items[0],'主攻：英语口语');
assert.equal(outcome('quarterly',createRecord('quarterly','2027-Q1')).every(x=>x.items.length===0),true);
console.log('Review model checks passed: rollover, independent records, validation, outcomes and allocations.');
