import assert from 'node:assert/strict';
import {upgradeTemplate,TEMPLATE_REVISION} from '../docs/template-update.js';
import {defaults} from '../docs/defaults.js';
const custom={id:'my-custom-event',day:2,start:'16:00',end:'17:00',title:'自定义任务',color:'blue',items:['保持内容']};
const old={version:1,events:[{id:'template-20',day:5,start:'09:00',end:'11:00',title:'经济财务周／月／季复盘',color:'gold',locked:true},custom]};
const result=upgradeTemplate(old);
assert.equal(result.templateRevision,TEMPLATE_REVISION);
assert.deepEqual(result.events.find(e=>e.id===custom.id),custom);
assert.equal(result.events.find(e=>e.id==='template-20').start,'09:30');
assert.equal(result.events.find(e=>e.id==='template-20').end,'11:30');
assert.equal(result.events.find(e=>e.id==='template-20').locked,true);
assert.equal(old.events[0].start,'09:00');
assert.equal(result.events.filter(e=>e.id.startsWith('q4-skills-weekday')).length,5);
assert.ok(result.events.filter(e=>e.id.startsWith('q4-skills-weekday')).every(e=>e.flex===true));
assert.equal(result.events.find(e=>e.id==='q4-skills-saturday').start,'08:00');
assert.equal(result.events.find(e=>e.id==='weekly-saturday-shopping').start,'11:30');
assert.deepEqual(upgradeTemplate(result),result);
const customized=structuredClone(result);customized.events=customized.events.filter(e=>e.id!=='q4-skills-saturday');
assert.deepEqual(upgradeTemplate(customized),customized);
assert.equal(new Set(defaults.map((e,i)=>e.id||'template-'+i)).size,defaults.length);
console.log('Template migration: custom data preserved, schedule updated, flexible slots added once, later edits preserved.');
